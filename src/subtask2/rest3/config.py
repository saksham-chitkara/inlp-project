"""
config.py
---------
Configuration for Subtask 2: Syllogistic Reasoning with Relevant Premise
Retrieval.

Architecture:
  - JointSyllogismClassifier: XLM-RoBERTa encoder (shared with subtask1)
    with two heads:
      Head 1 (validity):  Linear(768 → 2)  cross-entropy loss
      Head 2 (premises):  Linear(768 → 1) per-premise  BCEWithLogitsLoss
  - Initialized from the pretrained subtask1 checkpoint (encoder + validity
    head), with the premise head randomly initialized.
  - Dataset generated from subtask1 training data by injecting distractor
    premises (Technique 1: Llama LLM; Technique 2: cross-contamination).

Training objective:
  Total loss = α * CE(validity) + β * BCE(per-premise relevance)
  We compute BCE only over actual premise positions (masked loss).
"""

import os

# ─── Paths ───────────────────────────────────────────────────────────────────
BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# Input: subtask1 training data (source for distractor injection)
S1_TRAIN_DATA_PATH = os.path.join(
    BASE_DIR, "semeval_2026_task_11", "train_data", "subtask 1", "train_data.json"
)

# Test data: subtask2 (190 items, 5-8 premises each)
TEST_DATA_PATH = os.path.join(
    BASE_DIR, "semeval_2026_task_11", "test_data", "subtask 2", "test_data_subtask_2.json"
)

# Subtask2 outputs
OUTPUT_DIR = os.path.join(BASE_DIR, "src", "subtask2", "outputs")
os.makedirs(OUTPUT_DIR, exist_ok=True)

# Generated training dataset (from dataset_generator.py)
GENERATED_TRAIN_PATH = os.path.join(OUTPUT_DIR, "generated_train_data.json")

# Model checkpoint (fine-tuned JointSyllogismClassifier)
MODEL_SAVE_DIR = os.path.join(OUTPUT_DIR, "model_checkpoint")
os.makedirs(MODEL_SAVE_DIR, exist_ok=True)

# Subtask1 checkpoint to initialize from
S1_MODEL_SAVE_DIR = os.path.join(BASE_DIR, "src", "subtask1", "outputs", "model_checkpoint")
S1_STEERING_VECTORS_PATH = os.path.join(BASE_DIR, "src", "subtask1", "outputs", "steering_vectors.pt")
S1_QUASAR_TEST_CACHE = os.path.join(BASE_DIR, "src", "subtask1", "outputs", "quasar_test_cache.json")
