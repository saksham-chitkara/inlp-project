# Subtask2-specific QuaSAR cache (for subtask2 test items, generated by generate_quasar_subtask2.py)
S2_QUASAR_TEST_CACHE = os.path.join(OUTPUT_DIR, "quasar_s2_test_cache.json")

# Predictions output
PREDICTIONS_APPROACH1_PATH = os.path.join(OUTPUT_DIR, "predictions_approach1.json")
PREDICTIONS_APPROACH2_PATH = os.path.join(OUTPUT_DIR, "predictions_approach2.json")
EVAL_RESULTS_PATH = os.path.join(OUTPUT_DIR, "eval_results.json")

# ─── Dataset Generation ───────────────────────────────────────────────────────
# Number of distractor premises to inject per source item.
# Test set has avg 5.91 total premises (2 original + 3-4 distractors → 5-6 total).
# So we target 4-5 distractors → 6-7 total premises per item, matching test distribution.
MIN_DISTRACTORS = 4
MAX_DISTRACTORS = 5
# How many augmented samples to create per original training item
SAMPLES_PER_ITEM = 2   # → 960 × 2 = 1920 generated training examples

# ─── Model ───────────────────────────────────────────────────────────────────
# Shared with subtask1
MODEL_NAME = "xlm-roberta-base"
NUM_LABELS = 2              # 0=invalid, 1=valid
MAX_SEQ_LEN = 512           # longer for multi-premise syllogisms
MAX_PREMISES = 8            # maximum number of premises expected
DROPOUT_RATE = 0.3
HF_CACHE_DIR = os.environ.get("HF_HOME", None)

# ─── Training ─────────────────────────────────────────────────────────────────
BATCH_SIZE = 8
EVAL_BATCH_SIZE = 16
NUM_EPOCHS = 30
# Differential learning rates: encoder already fine-tuned on subtask1
ENCODER_LR = 1e-5           # lowered: reduce overfitting on generated data
HEAD_LR = 1e-4              # premise head is randomly initialized
WEIGHT_DECAY = 0.02         # stronger regularization
WARMUP_RATIO = 0.1
MAX_GRAD_NORM = 1.0
VALIDATION_SPLIT = 0.0      # 0 = use test data as validation (real distribution)
SEED = 42
USE_FP16 = True
GRADIENT_ACCUMULATION_STEPS = 1

# ─── Multi-task loss weights ─────────────────────────────────────────────────
VALIDITY_LOSS_WEIGHT = 0.5  # α
PREMISE_LOSS_WEIGHT  = 0.5  # β
# Positive premise weight in BCEWithLogitsLoss.
# With avg 6 premises per item, 2 relevant, 50% valid items:
#   overall positive fraction ≈ 50% × 2/6 ≈ 16.7%
#   pos_weight ≈ (1-0.167)/0.167 ≈ 5.0
PREMISE_POS_WEIGHT = 5.0

# ─── QuaSAR ──────────────────────────────────────────────────────────────────
USE_QUASI_SYMBOLIC = True
ABSTRACT_SEP = " </s> "
QUASAR_MODE = "full"
SPACY_MODEL = "en_core_web_sm"

# ─── Activation Steering (inherited from subtask1 vectors) ───────────────────
# We load and apply the subtask1 steering vectors (same encoder, same direction)
USE_ACTIVATION_STEERING = True
STEERING_LAYERS = [11]
STEERING_KNN = 10

# ─── Labels ──────────────────────────────────────────────────────────────────
LABEL2ID = {False: 0, True: 1}
ID2LABEL  = {0: False, 1: True}

# ─── LLM for dataset generation ──────────────────────────────────────────────
